#!/usr/bin/env node
// Generates typed ABI modules for the web app from the Foundry build output.
//
//   node scripts/abi.mjs            # reads ../out (run `forge build` at the repo root first)
//   OUT_DIR=/path/to/out node scripts/abi.mjs
//
// Each contract becomes src/abi/<name>.ts exporting `<name>Abi` as a const, so viem/wagmi infer
// argument and return types from it.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const outDir = resolve(process.env.OUT_DIR ?? join(here, '..', '..', 'out'))
const target = join(here, '..', 'src', 'abi')

const contracts = [
  { file: 'HmmMine.sol', contract: 'HmmMine', name: 'hmmMine' },
  { file: 'SwarmOracleAdapter.sol', contract: 'SwarmOracleAdapter', name: 'swarmOracleAdapter' },
  { file: 'HmmToken.sol', contract: 'HmmToken', name: 'hmmToken' },
  { file: 'GenesisForwarder.sol', contract: 'GenesisForwarder', name: 'genesisForwarder' },
]

if (!existsSync(outDir)) {
  console.error(`No Foundry output at ${outDir}. Run \`forge build\` in the repository root first.`)
  process.exit(1)
}
mkdirSync(target, { recursive: true })

const index = []
for (const { file, contract, name } of contracts) {
  const path = join(outDir, file, `${contract}.json`)
  if (!existsSync(path)) {
    console.error(`Missing artifact ${path}`)
    process.exit(1)
  }
  const { abi } = JSON.parse(readFileSync(path, 'utf8'))
  if (!Array.isArray(abi)) {
    console.error(`No ABI in ${path}`)
    process.exit(1)
  }
  const body =
    `// Generated by scripts/abi.mjs from out/${file}/${contract}.json. Do not edit by hand.\n` +
    `export const ${name}Abi = ${JSON.stringify(abi, null, 2)} as const\n`
  writeFileSync(join(target, `${name}.ts`), body)
  index.push(`export { ${name}Abi } from './${name}'`)
  console.log(`wrote src/abi/${name}.ts (${abi.length} entries)`)
}
writeFileSync(join(target, 'index.ts'), `// Generated by scripts/abi.mjs. Do not edit by hand.\n${index.join('\n')}\n`)
